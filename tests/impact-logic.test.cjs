const assert = require('node:assert/strict');
const {createImpactEngine} = require('../impact-logic.js');
const policy = require('../impact-policy.json');
const nodes=[{id:'source',type:'actor'},{id:'water',type:'actor'},{id:'food',type:'actor'},{id:'medicine',type:'actor'},{id:'device',type:'actor'},{id:'call',type:'actor'},{id:'p:one',type:'persona'},{id:'p:community',type:'persona'},{id:'vendor',type:'provider'}];
const units=[['water','water',false],['food','food',false],['medicine','remedies',false],['device','remedies',false],['call',null,true]].map(([id,essential_domain,critical_response])=>({id,nodes:[id],essential_domain,critical_response}));
const engine=createImpactEngine({policy:{...policy,societal_units:units},nodes,edges:[],active:()=>false});
const state={seed:'source',time:0,duration:48,impactArea:'local'};
const result=(starts)=>({starts:Object.fromEntries(nodes.map(n=>[n.id,starts[n.id]??Infinity]))});
assert.equal(engine.summarize(result({}),state).level,'none');
assert.equal(engine.summarize(result({'p:one':0}),state).level,'green');
assert.equal(engine.summarize(result({'p:one':0}),{...state,impactArea:'regional'}).level,'green');
assert.equal(engine.summarize(result({water:0}),state).level,'yellow');
assert.equal(engine.summarize(result({water:0}),{...state,impactArea:'regional'}).level,'red');
assert.equal(engine.summarize(result({medicine:0,device:0}),state).level,'yellow'); // same essential domain, no double counting
assert.equal(engine.summarize(result({water:0,medicine:0}),state).level,'red');
assert.equal(engine.summarize(result({call:0}),state).level,'red');
assert.equal(engine.summarize(result({water:12,food:24}),{...state,time:23.5}).level,'yellow');
assert.equal(engine.summarize(result({water:12,food:24}),{...state,time:24}).level,'red');
assert.equal(engine.summarize(result({water:12,food:24}),{...state,time:48}).level,'none');
assert.equal(engine.summarize(result({vendor:0}),{...state,seed:'vendor'}).level,'unknown');
const timeline=engine.timeline(result({water:12,food:24}),state);
assert.deepEqual(timeline.first,{green:null,yellow:12,red:24});
assert.equal(timeline.segments[0].start,0);assert.equal(timeline.segments.at(-1).end,336);
assert.equal(timeline.segments.reduce((sum,x)=>sum+x.end-x.start,0),336);
assert.equal(timeline.segments.at(-1).level,'none');
assert.equal(engine.timeline(result({water:400}),{...state,duration:720}).first.yellow,null);
const edges=[{a:'water',b:'source'},{a:'food',b:'source'},{a:'p:one',b:'water'}];
const nested=createImpactEngine({policy:{...policy,societal_units:units},nodes,edges,active:()=>true});
const a=nested.assess(result({source:0,water:0,food:0,'p:one':0}),state);
assert.equal(a.nodeLevels.source,'red');assert.equal(a.nodeLevels.water,'yellow');assert.equal(a.nodeLevels['p:one'],'green');
console.log('PASS: scope rules, no double counting, response loss, time boundaries, fixed 336 h, unknown, and node-specific downstream consequences.');
